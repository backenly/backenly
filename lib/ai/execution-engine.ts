/**
 * Create database table directly in workspace database
 */
async function createDatabaseTable(
  tableInfo: string | any,
  projectId: string
): Promise<ExecutionResult> {
  try {
    const { getWorkspaceDatabaseNames } = await import('@/lib/services/databaseProvisioning')
    const { executeInWorkspaceSchema } = await import('@/lib/services/workspaceDatabase')
    const { prisma } = await import('@/lib/db')
    
    // Parse table info - could be JSON object, JSON string, or natural language
    let tableName: string
    let columns: Array<{ name: string; type: string; nullable?: boolean; primary?: boolean }>
    
    // If tableInfo is already an object, use it directly
    if (typeof tableInfo === 'object' && tableInfo !== null) {
      tableName = tableInfo.tableName || tableInfo.name
      columns = tableInfo.columns || tableInfo.schema
      console.log(`📝 Received table object:`, { tableName, columnCount: columns?.length })
    } else {
      // It's a string - try parsing as JSON first
      try {
        const parsed = JSON.parse(tableInfo)
        tableName = parsed.tableName || parsed.name
        columns = parsed.columns || parsed.schema
      } catch {
        // Parse from natural language (e.g., "create a review table with id, title, content, rating columns")
        const match = tableInfo.match(/(?:create|table)\s+(?:a\s+|an\s+)?([\w_]+)/i)
        if (!match) {
          throw new Error('Could not extract table name from request')
        }
        tableName = match[1].toLowerCase()
        
        // Generate basic schema
        columns = [
          { name: 'id', type: 'SERIAL', primary: true },
          { name: 'created_at', type: 'TIMESTAMP', nullable: false },
          { name: 'updated_at', type: 'TIMESTAMP', nullable: false },
        ]
        
        // Try to extract column names from description
        const columnMatches = tableInfo.match(/(?:with|columns?|fields?)\s+([^.]+)/i)
        if (columnMatches) {
          const columnNames = columnMatches[1]
            .split(/[,;]|\s+and\s+/i)
            .map(c => c.trim().replace(/\s+columns?$/i, ''))
            .filter(Boolean)
          
          columnNames.forEach(colName => {
            if (!['id', 'created_at', 'updated_at'].includes(colName.toLowerCase())) {
              // Guess column type from name
              let type = 'TEXT'
              if (colName.toLowerCase().includes('email')) type = 'TEXT'
              else if (colName.toLowerCase().includes('password')) type = 'TEXT'
              else if (colName.toLowerCase().includes('rating') || colName.toLowerCase().includes('count')) type = 'INTEGER'
              else if (colName.toLowerCase().includes('price') || colName.toLowerCase().includes('amount')) type = 'DECIMAL(10,2)'
              else if (colName.toLowerCase().includes('date')) type = 'TIMESTAMP'
              else if (colName.toLowerCase().includes('is_') || colName.toLowerCase().includes('active')) type = 'BOOLEAN'
              
              columns.push({ name: colName.toLowerCase(), type, nullable: true })
            }
          })
        }
      }
    }
    
    console.log(`🗄️ Creating table "${tableName}" with ${columns.length} columns`)
    
    // Get workspace database info
    const dbNames = getWorkspaceDatabaseNames(projectId)
    const targetSchema = dbNames.postgresSchema
    
    // Generate CREATE TABLE SQL
    const columnDefs = columns.map(col => {
      const parts = [
        col.name,
        col.type,
        col.primary ? 'PRIMARY KEY' : '',
        col.nullable === false ? 'NOT NULL' : '',
        col.name === 'created_at' ? 'DEFAULT CURRENT_TIMESTAMP' : '',
        col.name === 'updated_at' ? 'DEFAULT CURRENT_TIMESTAMP' : '',
      ].filter(Boolean)
      return parts.join(' ')
    }).join(',\n  ')
    
    const createTableSQL = `
CREATE TABLE IF NOT EXISTS "${targetSchema}"."${tableName}" (
  ${columnDefs}
);
`
    
    console.log(`📝 SQL:\n${createTableSQL}`)
    
    // Execute CREATE TABLE
    await executeInWorkspaceSchema(projectId, createTableSQL)
    
    // Save to platform metadata (check if exists first)
    const existingTable = await prisma.table.findFirst({
      where: {
        projectId,
        name: tableName,
        schema: targetSchema,
      },
    })
    
    if (!existingTable) {
      await prisma.table.create({
        data: {
          projectId,
          name: tableName,
          schema: targetSchema,
          description: `Table created by AI Assistant`,
        },
      })
    } else {
      console.log(`ℹ️ Table metadata already exists, skipping insert`)
    }
    
    console.log(`✅ Table "${tableName}" created successfully`)
    
    return {
      success: true,
      message: `Table "${tableName}" created in database with ${columns.length} columns`,
    }
  } catch (error: any) {
    console.error(`❌ Failed to create table:`, error)
    return {
      success: false,
      message: `Failed to create table: ${error.message}`,
      errors: [error.message],
    }
  }
}

/**
 * Insert mock data into an existing table
 */
async function insertMockData(
  dataInfo: string | any,
  projectId: string
): Promise<ExecutionResult> {
  try {
    const { getWorkspaceDatabaseNames } = await import('@/lib/services/databaseProvisioning')
    const { executeInWorkspaceSchema } = await import('@/lib/services/workspaceDatabase')
    
    let tableName: string
    let rows: Array<Record<string, any>>
    
    // Parse data info - could be object or JSON string
    if (typeof dataInfo === 'object' && dataInfo !== null) {
      // If it's an array, it's the rows directly
      if (Array.isArray(dataInfo)) {
        rows = dataInfo
        // Extract table name from first row or fail
        throw new Error('Table name not provided. Please specify tableName in the request.')
      } else {
        tableName = dataInfo.tableName || dataInfo.table
        rows = dataInfo.rows || dataInfo.data || []
        
        // If rows is still an object (not array), wrap it
        if (!Array.isArray(rows) && typeof rows === 'object') {
          rows = [rows]
        }
      }
    } else if (typeof dataInfo === 'string') {
      // Check if it's a description (not JSON)
      if (!dataInfo.trim().startsWith('{') && !dataInfo.trim().startsWith('[')) {
        // It's a description like "Insert sample data into the Addresses table"
        // Extract table name
        const tableMatch = dataInfo.match(/(?:into|to|in)\s+(?:the\s+)?([\w_]+)\s+table/i)
        if (tableMatch) {
          tableName = tableMatch[1]
          // Return error asking user to provide data
          return {
            success: false,
            message: `Please provide the actual data to insert. Example: "insert {userId: 1, street: '123 Main St', city: 'NY', state: 'CA', zipCode: '12345'} into ${tableName}"`,
            errors: ['No data provided in the request'],
          }
        } else {
          throw new Error('Could not extract table name from description. Please specify: "insert data into TABLE_NAME"')
        }
      }
      
      // Try parsing as JSON
      const parsed = JSON.parse(dataInfo)
      if (Array.isArray(parsed)) {
        rows = parsed
        throw new Error('Table name not provided. Please specify tableName in the request.')
      } else {
        tableName = parsed.tableName || parsed.table
        rows = parsed.rows || parsed.data
      }
    } else {
      throw new Error('Invalid data format provided')
    }
    
    if (!tableName) {
      throw new Error('Table name is required')
    }
    
    if (!rows || !Array.isArray(rows) || rows.length === 0) {
      throw new Error('No data rows provided')
    }
    
    console.log(`📝 Inserting ${rows.length} rows into table "${tableName}"`)
    
    // Get workspace database info
    const dbNames = getWorkspaceDatabaseNames(projectId)
    const targetSchema = dbNames.postgresSchema
    
    // Query actual table structure from PostgreSQL
    const { prisma } = await import('@/lib/db')
    
    console.log(`🔍 Querying actual columns for table "${tableName}" in schema "${targetSchema}"`)
    
    // First, find the actual table name (case-insensitive match)
    const tableExistsQuery = `
      SELECT table_name 
      FROM information_schema.tables 
      WHERE table_schema = '${targetSchema}' 
      AND LOWER(table_name) = LOWER('${tableName}');
    `
    
    const tableResults: Array<{ table_name: string }> = await prisma.$queryRawUnsafe(tableExistsQuery)
    
    if (tableResults.length === 0) {
      throw new Error(`Table "${tableName}" not found in schema "${targetSchema}". Please verify the table exists.`)
    }
    
    // Use the actual table name from database (correct casing)
    const actualTableName = tableResults[0].table_name
    if (actualTableName !== tableName) {
      console.log(`📝 Corrected table name: "${tableName}" → "${actualTableName}"`)
      tableName = actualTableName
    }
    
    // Now query columns for the correct table name
    const columnsQuery = `
      SELECT column_name, data_type 
      FROM information_schema.columns 
      WHERE table_schema = '${targetSchema}' 
      AND table_name = '${tableName}'
      ORDER BY ordinal_position;
    `
    
    const actualColumns: Array<{ column_name: string; data_type: string }> = await prisma.$queryRawUnsafe(columnsQuery)
    
    const actualColumnNames = actualColumns.map(c => c.column_name)
    console.log(`✅ Found ${actualColumns.length} columns:`, actualColumnNames.join(', '))
    
    // Map user-provided data to actual column names (case-insensitive match)
    const mappedRows = rows.map(row => {
      const mappedRow: Record<string, any> = {}
      
      // Match each provided column to actual column (case-insensitive + fuzzy)
      Object.entries(row).forEach(([key, value]) => {
        // Try exact match (case-insensitive)
        let actualCol = actualColumnNames.find(c => c.toLowerCase() === key.toLowerCase())
        
        // If no match, try fuzzy matching for common variations
        if (!actualCol) {
          const keyLower = key.toLowerCase()
          // zipCode → postalCode
          if (keyLower === 'zipcode' || keyLower === 'zip') {
            actualCol = actualColumnNames.find(c => c.toLowerCase() === 'postalcode')
          }
          // postalCode → zipCode
          else if (keyLower === 'postalcode') {
            actualCol = actualColumnNames.find(c => c.toLowerCase() === 'zipcode')
          }
          // user_id → userId
          else if (keyLower === 'user_id') {
            actualCol = actualColumnNames.find(c => c.toLowerCase() === 'userid')
          }
          // userId → user_id
          else if (keyLower === 'userid') {
            actualCol = actualColumnNames.find(c => c.toLowerCase() === 'user_id')
          }
        }
        
        if (actualCol) {
          mappedRow[actualCol] = value
          if (key !== actualCol) {
            console.log(`📝 Mapped "${key}" → "${actualCol}"`)
          }
        } else {
          console.warn(`⚠️ Column "${key}" not found in table, skipping`)
        }
      })
      
      // Add timestamps if not provided
      if (!mappedRow.createdAt && !mappedRow.created_at && actualColumnNames.some(c => c.toLowerCase() === 'createdat')) {
        const col = actualColumnNames.find(c => c.toLowerCase() === 'createdat')!
        mappedRow[col] = new Date().toISOString()
      }
      if (!mappedRow.updatedAt && !mappedRow.updated_at && actualColumnNames.some(c => c.toLowerCase() === 'updatedat')) {
        const col = actualColumnNames.find(c => c.toLowerCase() === 'updatedat')!
        mappedRow[col] = new Date().toISOString()
      }
      
      return mappedRow
    })
    
    // Generate INSERT statements
    const insertPromises = mappedRows.map(async (row) => {
      const columns = Object.keys(row)
      const values = Object.values(row)
      
      // Format values for SQL
      const formattedValues = values.map(v => {
        if (v === null) return 'NULL'
        if (typeof v === 'string') return `'${v.replace(/'/g, "''")}'`
        if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE'
        if (v instanceof Date) return `'${v.toISOString()}'`
        return v
      }).join(', ')
      
      const insertSQL = `
INSERT INTO "${targetSchema}"."${tableName}" (${columns.map(c => `"${c}"`).join(', ')})
VALUES (${formattedValues});
`
      
      console.log(`📝 SQL: ${insertSQL}`)
      return executeInWorkspaceSchema(projectId, insertSQL)
    })
    
    await Promise.all(insertPromises)
    
    console.log(`✅ Inserted ${rows.length} rows into "${tableName}"`)
    
    return {
      success: true,
      message: `Successfully inserted ${rows.length} rows into table "${tableName}"`,
    }
  } catch (error: any) {
    console.error(`❌ Failed to insert mock data:`, error)
    return {
      success: false,
      message: `Failed to insert data: ${error.message}`,
      errors: [error.message],
    }
  }
}

