/**
 * Execute a single action from the AI plan
 */
export async function executeAction(
  action: string,
  description: string,
  code: string | undefined,
  projectId: string,
  workspacePath: string
): Promise<ExecutionResult> {
  console.log(`🔧 Executing: ${action}`)
  console.log(`📝 Description: ${description}`)

  try {
    switch (action) {
      case 'CREATE_PRISMA_MODEL':
        return await createPrismaModel(code!, projectId, workspacePath)
      
      case 'CREATE_API_ROUTE':
        return await createAPIRoute(code!, description, projectId, workspacePath)
      
      case 'RUN_MIGRATION':
        return await runMigration(projectId, workspacePath)
      
      case 'MODIFY_ENV':
        return await modifyEnvFile(description, code!, projectId, workspacePath)
      
      case 'GENERATE_AUTH':
        return await generateAuthSetup(projectId, workspacePath)
      
      case 'CREATE_STORAGE_BUCKET':
        return await createStorageBucket(description, projectId)
      
      case 'CREATE_DATABASE_TABLE':
        return await createDatabaseTable(code || description, projectId)
      
      case 'INSERT_MOCK_DATA':
        return await insertMockData(code || description, projectId)

      // CREATE_API_DEFINITION is gone (2026-07-21). Under PostgREST the API IS
      // the schema: a table is reachable because it exists and the role holds a
      // grant, resolved from the PostgreSQL catalog per request. An ApiDefinition
      // row decided nothing and could only disagree with the catalog, so the
      // action now falls through to "unknown" rather than writing one.
      default:
        return {
          success: false,
          message: `Unknown action: ${action}`,
          errors: [`Action type "${action}" is not supported`],
        }
    }
  } catch (error: any) {
    console.error(`❌ Execution failed:`, error)
    return {
      success: false,
      message: `Execution failed: ${error.message}`,
      errors: [error.message],
    }
  }
}

/**
 * Create or update Prisma model in schema
 */
async function createPrismaModel(
  modelCode: string,
  projectId: string,
  workspacePath: string
): Promise<ExecutionResult> {
  const schemaPath = join(workspacePath, 'prisma', 'schema.prisma')
  const envPath = join(workspacePath, '.env')
  
  try {
    // Ensure prisma directory exists
    const prismaDir = join(workspacePath, 'prisma')
    if (!existsSync(prismaDir)) {
      mkdirSync(prismaDir, { recursive: true })
    }

    // Read existing schema or create default
    let existingSchema = ''
    if (existsSync(schemaPath)) {
      existingSchema = readFileSync(schemaPath, 'utf-8')
    } else {
      existingSchema = `// Prisma Schema for Project: ${projectId}
// Generated by Backenly AI

generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

`
    }

    // Extract model name from the new model code
    const modelNameMatch = modelCode.match(/model\s+(\w+)\s*{/)
    if (!modelNameMatch) {
      throw new Error('Could not extract model name from code')
    }
    const newModelName = modelNameMatch[1]
    
    // Check if model already exists in schema
    const modelRegex = new RegExp(`model\\s+${newModelName}\\s*{`, 'i')
    if (modelRegex.test(existingSchema)) {
      console.log(`⚠️ Model "${newModelName}" already exists in schema - skipping (idempotent)`)
      return {
        success: true,
        message: `Model "${newModelName}" already exists in schema (no changes needed)`,
        filesModified: [],
      }
    }
    
    // Append new model
    const updatedSchema = existingSchema + '\n' + modelCode + '\n'
    
    // Write to file
    writeFileSync(schemaPath, updatedSchema, 'utf-8')
    console.log(`✅ Prisma model written to: ${schemaPath}`)

    // 🔧 Create .env file with workspace-specific DATABASE_URL
    if (!existsSync(envPath)) {
      // Get the main DATABASE_URL and modify it to use workspace schema
      const mainDbUrl = process.env.DATABASE_URL || ''
      const workspaceSchema = `workspace_${projectId}`
      
      // Add schema parameter to the connection string
      const workspaceDbUrl = mainDbUrl.includes('?')
        ? `${mainDbUrl}&schema=${workspaceSchema}`
        : `${mainDbUrl}?schema=${workspaceSchema}`
      
      const envContent = `# Auto-generated by Backenly AI\nDATABASE_URL="${workspaceDbUrl}"\n`
      writeFileSync(envPath, envContent, 'utf-8')
      console.log(`✅ Created .env file with workspace DATABASE_URL`)
    }

    return {
      success: true,
      message: `Prisma model created successfully`,
      filesCreated: existingSchema === '' ? [schemaPath, envPath] : undefined,
      filesModified: existingSchema !== '' ? [schemaPath] : undefined,
    }
  } catch (error: any) {
    return {
      success: false,
      message: `Failed to create Prisma model: ${error.message}`,
      errors: [error.message],
    }
  }
}

