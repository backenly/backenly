/**
 * Environment files already in project workspaces, and the removal of the ones
 * Backenly wrote.
 *
 * POST /api/database/setup-workspace used to write a `.env` holding a database
 * connection string into a project's workspace, and the files sync copied it
 * into workspace_files. Neither happens now, and no workspace route serves,
 * lists, copies or archives an environment file (isEnvFile in ./paths). This
 * finds the copies made before that: on disk under the workspace root, and in
 * workspace_files.
 *
 * A file Backenly wrote starts with BACKENLY_ENV_HEADER. Only those are ever
 * removed. Any other environment file is reported for a person to decide; it
 * is no longer served either way. Contents are never returned, only whether a
 * file starts with the header.
 */
import { promises as fs } from 'fs'
import * as path from 'path'
import { prisma } from '@/lib/db/prisma'
import { isEnvFile, workspaceRoot } from './paths'

/** The first line of every `.env` setup-workspace wrote. */
export const BACKENLY_ENV_HEADER = '# Auto-generated by Backenly'

/** Directories a workspace scan never enters. */
const SKIPPED_DIRECTORIES = new Set(['node_modules', '.git', 'dist', '.next'])

export interface WorkspaceEnvFile {
  where: 'disk' | 'database'
  /** The workspace directory's name on disk; the row's projectId in the database. */
  projectId: string
  /** Relative to the project's workspace on disk; the row's path in the database. */
  file: string
  writtenByBackenly: boolean
  /** Absolute path, for a file on disk. */
  fullPath?: string
  /** workspace_files id, for a row. */
  rowId?: string
}

/** Every environment file in every project workspace, on disk and in workspace_files. */
export async function findWorkspaceEnvFiles(): Promise<WorkspaceEnvFile[]> {
  return [...(await onDisk()), ...(await inDatabase())]
}

async function onDisk(): Promise<WorkspaceEnvFile[]> {
  const root = workspaceRoot()
  let projects
  try {
    projects = await fs.readdir(root, { withFileTypes: true })
  } catch (error: any) {
    if (error?.code === 'ENOENT') return []
    throw error
  }

  const found: WorkspaceEnvFile[] = []
  for (const project of projects) {
    if (!project.isDirectory()) continue
    const base = path.join(root, project.name)
    // Dirent types do not follow symbolic links, so a link is never entered or read.
    const walk = async (dir: string): Promise<void> => {
      for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name)
        if (entry.isDirectory()) {
          if (!SKIPPED_DIRECTORIES.has(entry.name)) await walk(full)
        } else if (entry.isFile() && isEnvFile(entry.name)) {
          const content = await fs.readFile(full, 'utf8')
          found.push({
            where: 'disk',
            projectId: project.name,
            file: path.relative(base, full),
            writtenByBackenly: content.startsWith(BACKENLY_ENV_HEADER),
            fullPath: full,
          })
        }
      }
    }
    await walk(base)
  }
  return found
}

async function inDatabase(): Promise<WorkspaceEnvFile[]> {
  // Narrowed in SQL, decided by isEnvFile: `.env` in a path is rare, so only
  // those rows' contents are read.
  const rows = await prisma.workspaceFile.findMany({
    where: { path: { contains: '.env', mode: 'insensitive' } },
    select: { id: true, projectId: true, path: true, content: true },
  })
  return rows
    .filter((row) => isEnvFile(row.path))
    .map((row) => ({
      where: 'database' as const,
      projectId: row.projectId,
      file: row.path,
      writtenByBackenly: row.content.startsWith(BACKENLY_ENV_HEADER),
      rowId: row.id,
    }))
}

/** Remove the files and rows Backenly wrote; leave every other one. */
export async function removeBackenlyEnvFiles(found: WorkspaceEnvFile[]): Promise<{ files: number; rows: number }> {
  let files = 0
  for (const f of found) {
    if (f.where !== 'disk' || !f.writtenByBackenly || !f.fullPath) continue
    // Read again just before removing: only a file that still starts with the
    // header is Backenly's to remove.
    const content = await fs.readFile(f.fullPath, 'utf8').catch(() => null)
    if (content === null || !content.startsWith(BACKENLY_ENV_HEADER)) continue
    await fs.unlink(f.fullPath)
    files++
  }

  const ids = found.filter((f) => f.where === 'database' && f.writtenByBackenly && f.rowId).map((f) => f.rowId!)
  // history: workspace_files copies of the .env setup-workspace wrote; operator cleanup at release, not a change to a project's backend.
  const { count: rows } = ids.length
    ? await prisma.workspaceFile.deleteMany({ where: { id: { in: ids }, content: { startsWith: BACKENLY_ENV_HEADER } } })
    : { count: 0 }

  return { files, rows }
}
